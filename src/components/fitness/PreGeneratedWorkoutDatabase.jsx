export function findWorkoutById(id) {
  return ALL_420_WORKOUTS.find(w => w.id === parseInt(id));
}

export function findWorkoutsByFilters(target, level, goal, duration) {
  return ALL_420_WORKOUTS.filter(w => {
    const matchTarget = !target || w.target === target;
    const matchLevel = !level || w.level === level;
    const matchGoal = !goal || w.goal === goal;
    const matchDuration = !duration || w.duration === duration;
    return matchTarget && matchLevel && matchGoal && matchDuration;
  });
}


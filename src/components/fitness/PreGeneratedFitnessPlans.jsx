// Retrieval function
export function getPreGeneratedFitnessPlan(targetArea, fitnessLevel, durationMinutes, fitnessGoal) {
  const plan = PRE_GENERATED_FITNESS_PLANS.find(
    p => p.targetArea === targetArea && 
         p.fitnessLevel === fitnessLevel && 
         p.durationMinutes === durationMinutes && 
         p.fitnessGoal === fitnessGoal
  );

  if (!plan) {
    // Fallback - return a basic plan
    return {
      targetArea,
      fitnessLevel,
      durationMinutes,
      fitnessGoal,
      planName: `${fitnessLevel} ${targetArea} ${fitnessGoal} - ${durationMinutes} min`,
      exercises: [
        { name: "Squats", sets: 3, reps: 12, rest: 60 },
        { name: "Push-ups", sets: 3, reps: 10, rest: 60 },
        { name: "Plank", sets: 3, reps: "45 sec", rest: 45 }
      ]
    };
  }

  return plan;
}